#!/bin/bash

# Регулярное выражение для проверки числа
RE='^-?[0-9]+([.][0-9]+)?$'

# 1. Проверка количества аргументов
if [ "$#" -ne 2 ]; then
    echo "Ошибка: необходимо передать ровно два числа."
    exit 1
fi

# 2. Валидация аргументов
for arg in "$1" "$2"; do
    if [[ ! $arg =~ $RE ]]; then
        echo "Ошибка: '$arg' не является валидным числом."
        exit 1
    fi
done

# 3. Вычисление суммы через awk (он надежнее bc в плане предустановки)
# Мы передаем переменные через флаг -v, чтобы избежать проблем с экранированием
sum=$(awk -v n1="$1" -v n2="$2" 'BEGIN { print n1 + n2 }')

echo "Результат: $sum"
