#!/bin/bash

if ! command -v bc &> /dev/null; then
    echo "Ошибка: утилита 'bc' не найдена. Пожалуйста, установите её или используйте awk."
    exit 1
fi

# Регулярное выражение для проверки числа (целого или дробного, положительного или отрицательного)
RE='^-?[0-9]+([.][0-9]+)?$'

# 1. Проверяем, что передано ровно два аргумента
if [ "$#" -ne 2 ]; then
    echo "Ошибка: необходимо передать ровно два числа."
    echo "Использование: $0 <число1> <число2>"
    exit 1
fi

# 2. Проверяем каждый аргумент на соответствие регулярному выражению
for arg in "$1" "$2"; do
    if [[ ! $arg =~ $RE ]]; then
        echo "Ошибка: '$arg' не является числом."
        exit 1
    fi
done

# 3. Считаем сумму через bc и выводим результат
# echo поможет передать выражение в bc
sum=$(echo "$1 + $2" | bc)

echo "Результат: $sum"